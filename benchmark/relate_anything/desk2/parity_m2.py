"""Debian export venv: horse PyTorch/ONNX parity on identical saved native PIL inputs."""
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
import numpy as np
import onnxruntime as ort
import torch

ROOT = Path('/termux-home')
REPO = ROOT / 'ext/RelateAnything'
MODEL = ROOT / 'models/relate_anything/relsgg-vits16'
sys.path.insert(0, str(REPO))
from deploy.export_onnx import RelSGGExport
from relsgg.api import RelateAnything

torch.set_num_threads(2)
torch.backends.mha.set_fastpath_enabled(False)
with np.load(MODEL / 'horse_native_feed.npz') as z:
    feed = {name: z[name] for name in z.files}
with np.load(MODEL / 'predicate_bank.npz', allow_pickle=True) as z:
    names = list(map(str, z['default']))
ra = RelateAnything.from_checkpoint(str(MODEL / 'model.pth'), names, device='cpu',
                                    weights='ema', img_size=448, strict=True, embeddings=feed['W'])
wrapper = RelSGGExport(ra.model.eval(), vocab_as_input=True).eval()
with torch.no_grad():
    reference = wrapper(*(torch.from_numpy(feed[n]) for n in ('image', 'boxes', 'box_counts', 'W', 'alpha')))
options = ort.SessionOptions()
options.intra_op_num_threads = 2
session = ort.InferenceSession(str(MODEL / 'relateanything.onnx'), options, providers=['CPUExecutionProvider'])
outputs = ['pred_logits', 'pair_logits', 'sub_idx', 'obj_idx', 'valid_mask']
got = session.run(outputs, feed)
threshold = 1e-3  # absolute logit tolerance, >14x published M1 6.87e-5, still <=0.00025 uncalibrated score error.
result = {'threshold_abs_logits': threshold, 'reason': 'float32 CPU/export roundoff allowance; score sigmoid Lipschitz <=1/4',
          'sample': 'assets/reel/images/horse.jpg', 'boxes': [[470,130,650,630],[90,310,1010,875]],
          'inputs': 'horse_native_feed.npz generated by native desk_check.preprocess',
          'deltas': {}, 'exact_matches': {}}
for name, ref, actual in zip(outputs, reference, got):
    expected = ref.numpy()
    if expected.dtype in (np.dtype('bool'), np.dtype('int64')):
        result['exact_matches'][name] = bool(np.array_equal(expected, actual))
    else:
        result['deltas'][name] = float(np.max(np.abs(expected - actual)))
result['passed'] = all(np.isfinite(d) and d <= threshold for d in result['deltas'].values()) and all(result['exact_matches'].values())
print(json.dumps(result, indent=2), flush=True)
(MODEL / 'horse_parity.json').write_text(json.dumps(result, indent=2) + '\n')
if not result['passed']:
    raise SystemExit('STOP M2: parity failure')
